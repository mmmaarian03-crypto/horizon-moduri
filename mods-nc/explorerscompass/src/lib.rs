/// A structure start the world made: which structure, and the chunk that owns it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Start {
    pub structure: String,
    pub chunk: [i32; 2],
}

/// What the search reads of the world.
pub trait StructureWorld {
    /// The structure starts of a chunk (`checkStructurePresence` + `getStartForStructure`).
    fn starts(&mut self, chunk_x: i32, chunk_z: i32) -> Vec<Start>;
    /// `getRingPositionsFor(placement)` of a rings set (strongholds).
    fn rings(&mut self, set: &str) -> Vec<[i32; 2]>;
    /// The world seed.
    fn seed(&self) -> i64;
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Dir {
    Up,
    North,
    East,
    South,
    West,
}
impl Dir {
    fn clockwise(self) -> Dir {
        match self {
            Dir::North => Dir::East,
            Dir::East => Dir::South,
            Dir::South => Dir::West,
            Dir::West => Dir::North,
            Dir::Up => Dir::Up,
        }
    }
}

/// How a search ended.
#[derive(Clone, Debug, PartialEq)]
pub enum Outcome {
    /// `ExplorersCompassItem.succeed(stack, structureKey, isGroup, x, z, prevPos, samples, displayCoordinates)`.
    Found { structure: String, x: i32, z: i32, prev_pos: Vec<Pos>, samples: i32 },
    /// `setNotFound(radius, samples)` (the radius rounded to 250) after the last worker.
    NotFound { radius: i32, samples: i32 },
}

enum Kind {
    Spread { spacing: i32, separation: i32, salt: i32, triangular: bool, start_section: [i32; 2], x: i32, z: i32, length: i32 },
    Rings { set: String, chunks: Option<Vec<[i32; 2]>>, index: usize, min_distance: f64, closest: Option<(Pos, String)> },
    Generic { chunk_x: i32, chunk_z: i32, length: i32, next_length: f64, direction: Dir },
}

/// One `StructureSearchWorker`.
struct Worker {
    kind: Kind,
    structures: Vec<String>,
    samples: i32,
    finished: bool,
    last_radius_threshold: i32,
    current: Pos,
}

/// What one `doWork` call of a worker ended in.
enum Step {
    Working,
    Found(Pos, String),
    Failed,
}

pub fn round_radius(radius: i32, round_to: i32) -> i32 {
    (radius / round_to) * round_to
}

/// `SearchWorkerManager` and the workers it makes (one per placement among the requested structures).
pub struct Search {
    workers: VecDeque<Worker>,
    start: Pos,
    prev_pos: Vec<Pos>,
    pub max_radius: i64,
    pub max_samples: i64,
    pub max_next: i64,
    /// `setSearchRadius` calls made while working, taken by the adapter.
    pub radius_updates: Vec<i32>,
    /// The structure key written when nothing is found.
    pub key: String,
    began: bool,
}

impl Search {
    /// `createWorkers`: `requested` structures (in order) and the sets each one is in (those that can generate here).
    /// `key` is `structureOrGroupId`.
    pub fn new(key: &str, requested: &[String], sets_of: &dyn Fn(&str) -> Vec<SetDef>, start: Pos, prev_pos: Vec<Pos>) -> Search {
        let mut by_set: Vec<SetDef> = Vec::new();
        for s in requested {
            for set in sets_of(s) {
                match by_set.iter_mut().find(|x| x.id == set.id) {
                    Some(x) => x.structures.push(s.clone()),
                    None => by_set.push(SetDef { structures: vec![s.clone()], ..set }),
                }
            }
        }
        let workers = by_set
            .into_iter()
            .map(|set| {
                let kind = match set.placement {
                    Placement::RandomSpread { spacing, separation, salt, triangular } => Kind::Spread {
                        spacing,
                        separation,
                        salt,
                        triangular,
                        start_section: [start[0] >> 4, start[2] >> 4],
                        x: 0,
                        z: 0,
                        length: 0,
                    },
                    Placement::Rings => Kind::Rings { set: set.id.clone(), chunks: None, index: 0, min_distance: f64::MAX, closest: None },
                    Placement::Generic => Kind::Generic { chunk_x: start[0] >> 4, chunk_z: start[2] >> 4, length: 0, next_length: 1.0, direction: Dir::Up },
                };
                Worker { kind, structures: set.structures, samples: 0, finished: false, last_radius_threshold: 0, current: start }
            })
            .collect();
        Search {
            workers,
            start,
            prev_pos,
            max_radius: config::GENERAL_MAX_RADIUS,
            max_samples: config::GENERAL_MAX_SAMPLES,
            max_next: config::GENERAL_MAX_NEXT_SEARCHES,
            radius_updates: Vec::new(),
            key: key.to_owned(),
            began: false,
        }
    }

    /// No worker: the placements of the structures are not in this dimension (`workerManager.start()` is false).
    pub fn is_empty(&self) -> bool {
        self.workers.is_empty()
    }
    pub fn prev_pos(&self) -> &[Pos] {
        &self.prev_pos
    }

    fn radius_of(&self, w: &Worker) -> i32 {
        distance(self.start, w.current[0], w.current[2])
    }
    /// `StructureSearchWorker.hasWork` without the placement kind's own condition.
    fn base_work(&self, w: &Worker) -> bool {
        !w.finished && self.prev_pos.len() as i64 <= self.max_next && i64::from(w.samples) < self.max_samples
    }
    /// `hasWork()` of a spread or generic worker (rings have their own, see `step_kind`).
    fn has_work(&self, w: &Worker) -> bool {
        self.base_work(w) && i64::from(self.radius_of(w)) < self.max_radius
    }
    fn should_ignore(&self, pos: Pos) -> bool {
        self.prev_pos.contains(&pos)
    }
    /// `getStructureGeneratingAt(chunkPos)`.
    fn generating_at(w: &Worker, world: &mut impl StructureWorld, cx: i32, cz: i32) -> Option<(Pos, String)> {
        let starts = world.starts(cx, cz);
        for s in &w.structures {
            if let Some(st) = starts.iter().find(|x| &x.structure == s) {
                return Some(([st.chunk[0] * 16, 0, st.chunk[1] * 16], s.clone()));
            }
        }
        None
    }
    /// `StructureSearchWorker.doWork`'s first part: the radius shown every 250 blocks.
    fn radius_report(&mut self, wi: usize) {
        let radius = self.radius_of(&self.workers[wi]);
        if radius > 250 && radius / 250 > self.workers[wi].last_radius_threshold {
            self.radius_updates.push(round_radius(radius, 250));
            self.workers[wi].last_radius_threshold = radius / 250;
        }
    }

    /// `start()` of the first worker: with no radius it fails at once, and the next one starts.
    /// `Some` when the whole search ended during it.
    pub fn begin(&mut self) -> Option<Outcome> {
        self.began = true;
        if self.workers.is_empty() {
            return Some(Outcome::NotFound { radius: 0, samples: 0 });
        }
        self.start_current()
    }
    fn start_current(&mut self) -> Option<Outcome> {
        loop {
            let Some(w) = self.workers.front() else { return None };
            if self.max_radius > 0 {
                return None;
            }
            // `start()` with maxRadius 0: `fail()` -> `workerManager.pop()`, `start()`...
            let (radius, samples) = (round_radius(self.radius_of(w), 250), w.samples);
            self.workers.pop_front();
            if self.workers.is_empty() {
                return Some(Outcome::NotFound { radius, samples });
            }
        }
    }
    /// A worker failed: the next one starts, else nothing was found.
    fn failed(&mut self) -> Option<Outcome> {
        let w = self.workers.pop_front()?;
        let (radius, samples) = (round_radius(self.radius_of(&w), 250), w.samples);
        if self.workers.is_empty() {
            return Some(Outcome::NotFound { radius, samples });
        }
        self.start_current().or(None)
    }

    /// One `doWork()` of the current worker. `Some` when the search ended.
    pub fn do_work(&mut self, world: &mut impl StructureWorld) -> Option<Outcome> {
        if !self.began {
            if let Some(o) = self.begin() {
                return Some(o);
            }
        }
        if self.workers.is_empty() {
            return Some(Outcome::NotFound { radius: 0, samples: 0 });
        }
        match self.step(world) {
            Step::Working => None,
            Step::Found(pos, structure) => {
                let w = &self.workers[0];
                let samples = w.samples;
                Some(Outcome::Found { structure, x: pos[0], z: pos[2], prev_pos: self.prev_pos.clone(), samples })
            }
            Step::Failed => self.failed(),
        }
    }

    fn step(&mut self, world: &mut impl StructureWorld) -> Step {
        self.radius_report(0);
        // Rings: the ring chunks are asked for the first time here (the worker knows them from its creation in the original).
        if let Kind::Rings { set, chunks, .. } = &mut self.workers[0].kind
            && chunks.is_none()
        {
            let got = world.rings(set);
            *chunks = Some(got);
        }
        let mut kind = std::mem::replace(&mut self.workers[0].kind, Kind::Generic { chunk_x: 0, chunk_z: 0, length: 0, next_length: 1.0, direction: Dir::Up });
        let result = self.step_kind(&mut kind, world);
        self.workers[0].kind = kind;
        result
    }

    fn step_kind(&mut self, kind: &mut Kind, world: &mut impl StructureWorld) -> Step {
        let seed = world.seed();
        match kind {
            Kind::Spread { spacing, separation, salt, triangular, start_section, x, z, length } => {
                if self.has_work(&self.workers[0]) {
                    let sample_x_edge = *x == -*length || *x == *length;
                    let sample_z_edge = *z == -*length || *z == *length;
                    if sample_x_edge || sample_z_edge {
                        let sx = start_section[0] + *spacing * *x;
                        let sz = start_section[1] + *spacing * *z;
                        let c = potential_chunk(*spacing, *separation, *salt, *triangular, seed, sx, sz);
                        self.workers[0].current = [c[0] * 16 + 8, 0, c[1] * 16 + 8];
                        let found = Self::generating_at(&self.workers[0], world, c[0], c[1]);
                        self.workers[0].samples += 1;
                        if let Some((pos, structure)) = found
                            && !self.should_ignore(pos)
                        {
                            self.prev_pos.push(pos);
                            self.workers[0].finished = true;
                            return Step::Found(pos, structure);
                        }
                    }
                    *z += 1;
                    if *z > *length {
                        *x += 1;
                        if *x > *length {
                            *length += 1;
                            *x = -*length;
                            *z = -*length;
                        } else {
                            *z = -*length;
                        }
                    }
                } else if !self.workers[0].finished {
                    self.workers[0].finished = true;
                    return Step::Failed;
                }
                if self.has_work(&self.workers[0]) {
                    return Step::Working;
                }
                if !self.workers[0].finished {
                    self.workers[0].finished = true;
                    return Step::Failed;
                }
                Step::Working
            }
            Kind::Rings { chunks, index, min_distance, closest, .. } => {
                let list = chunks.clone().unwrap_or_default();
                // No ring chunks at all: the original worker is dropped silently; here the search moves on.
                if list.is_empty() {
                    self.workers[0].finished = true;
                    return Step::Failed;
                }
                if self.base_work(&self.workers[0]) && *index < list.len() {
                    let c = list[*index];
                    self.workers[0].current = [c[0] * 16 + 8, 0, c[1] * 16 + 8];
                    let cur = self.workers[0].current;
                    // `startPos.distSqr(currentPos)`: with the heights of both.
                    let (dx, dy, dz) = (f64::from(self.start[0] - cur[0]), f64::from(self.start[1] - cur[1]), f64::from(self.start[2] - cur[2]));
                    let d = dx * dx + dy * dy + dz * dz;
                    if closest.is_none() || d < *min_distance {
                        let pair = Self::generating_at(&self.workers[0], world, c[0], c[1]);
                        if let Some((pos, structure)) = pair
                            && !self.should_ignore(pos)
                        {
                            *min_distance = d;
                            *closest = Some((pos, structure));
                        }
                    }
                    self.workers[0].samples += 1;
                    *index += 1;
                }
                if self.base_work(&self.workers[0]) && *index < list.len() {
                    return Step::Working;
                }
                self.workers[0].finished = true;
                match closest.take() {
                    Some((pos, structure)) => {
                        self.prev_pos.push(pos);
                        Step::Found(pos, structure)
                    }
                    None => Step::Failed,
                }
            }
            Kind::Generic { chunk_x, chunk_z, length, next_length, direction } => {
                if self.has_work(&self.workers[0]) {
                    match direction {
                        Dir::North => *chunk_z -= 1,
                        Dir::East => *chunk_x += 1,
                        Dir::South => *chunk_z += 1,
                        Dir::West => *chunk_x -= 1,
                        Dir::Up => {}
                    }
                    self.workers[0].current = [*chunk_x * 16 + 8, 0, *chunk_z * 16 + 8];
                    let pair = Self::generating_at(&self.workers[0], world, *chunk_x, *chunk_z);
                    if let Some((pos, structure)) = pair
                        && !self.should_ignore(pos)
                    {
                        self.prev_pos.push(pos);
                        self.workers[0].finished = true;
                        return Step::Found(pos, structure);
                    }
                    self.workers[0].samples += 1;
                    *length += 1;
                    if *length >= *next_length as i32 {
                        if *direction != Dir::Up {
                            *next_length += 0.5;
                            *direction = direction.clockwise();
                        } else {
                            *direction = Dir::North;
                        }
                        *length = 0;
                    }
                    // The generic worker reports the radius on its own, after the sample.
                    self.radius_report(0);
                }
                if self.has_work(&self.workers[0]) {
                    return Step::Working;
                }
                self.workers[0].finished = true;
                Step::Failed
            }
        }
    }
}

