/// What the teleport search reads of a column.
pub trait Column {
    /// `isFree`: air, fire, liquid or replaceable.
    fn free(&self, y: i32) -> bool;
    /// `level.isOutsideBuildHeight(y)`.
    fn outside(&self, y: i32) -> bool;
}

/// `findValidTeleportHeight`.
pub fn teleport_height(col: &impl Column, sea_level: i32) -> i32 {
    let valid = |y: i32| col.free(y) && col.free(y + 1) && !col.free(y - 1);
    let (mut up, mut down) = (sea_level, sea_level);
    while (!col.outside(up) || !col.outside(down)) && !(valid(up) || valid(down)) {
        up += 1;
        down -= 1;
    }
    if valid(up) {
        return up;
    }
    if valid(down) {
        return down;
    }
    256
}


