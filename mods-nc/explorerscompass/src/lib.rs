/// One row of the list: what `StructureSearchEntry` shows.
#[derive(Clone, Debug, PartialEq)]
pub struct Entry {
    pub key: String,
    /// `StructureUtils.getPrettyStructureName`.
    pub name: String,
    /// `StructureUtils.getPrettyStructureSource`.
    pub source: String,
    /// The group's key (`structureKeysToTypeKeys`, the structure set) and its pretty name.
    pub group_key: String,
    pub group: String,
    /// `StructureUtils.dimensionKeysToString`.
    pub dimensions: String,
    pub xp: i64,
}

/// `WordUtils.capitalize`: the first letter of each word (spaces separate words).
pub fn capitalize(text: &str) -> String {
    let mut out = String::new();
    let mut start = true;
    for c in text.chars() {
        if c.is_whitespace() {
            start = true;
            out.push(c);
        } else if start {
            out.extend(c.to_uppercase());
            start = false;
        } else {
            out.push(c);
        }
    }
    out
}


/// `StructureUtils.getPrettyStructureName`: the translation if there is one, else the path in words.
pub fn pretty_name(key: &str, translated: Option<String>) -> String {
    if config::CLIENT_TRANSLATE_STRUCTURE_NAMES
        && let Some(t) = translated
    {
        return t;
    }
    let path = key.split_once(':').map_or(key, |(_, p)| p);
    capitalize(&path.replace('_', " "))
}

/// The sortings, in the order of `ISorting.next()`: Name, Source, Dimension, Levels, Group.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Sorting {
    Name,
    Source,
    Dimension,
    Xp,
    Group,
}
impl Sorting {
    pub fn next(self) -> Sorting {
        match self {
            Sorting::Name => Sorting::Source,
            Sorting::Source => Sorting::Dimension,
            Sorting::Dimension => Sorting::Xp,
            Sorting::Xp => Sorting::Group,
            Sorting::Group => Sorting::Name,
        }
    }
    /// The language key (`string.explorerscompass.<key>`) and the English text of `getLocalizedName`.
    pub fn label(self) -> (&'static str, &'static str) {
        match self {
            Sorting::Name => ("name", "Name"),
            Sorting::Source => ("source", "Source"),
            Sorting::Dimension => ("dimension", "Dimension"),
            Sorting::Xp => ("levels", "Levels"),
            Sorting::Group => ("group", "Group"),
        }
    }
    pub fn compare(self, a: &Entry, b: &Entry) -> std::cmp::Ordering {
        match self {
            Sorting::Name => a.name.cmp(&b.name),
            Sorting::Source => a.source.cmp(&b.source),
            Sorting::Dimension => a.dimensions.cmp(&b.dimensions),
            Sorting::Xp => a.xp.to_string().cmp(&b.xp.to_string()),
            Sorting::Group => a.group_key.cmp(&b.group_key),
        }
    }
}

/// A rectangle of the screen in GUI pixels.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Rect {
    pub x: i32,
    pub y: i32,
    pub w: i32,
    pub h: i32,
}
impl Rect {
    pub fn new(x: i32, y: i32, w: i32, h: i32) -> Rect {
        Rect { x, y, w, h }
    }
    pub fn contains(&self, px: f32, py: f32) -> bool {
        px >= self.x as f32 && px < (self.x + self.w) as f32 && py >= self.y as f32 && py < (self.y + self.h) as f32
    }
}

/// `TransparentButton` / `RenderUtils.getBackgroundColor`: the alpha of the black fill for a state
/// (`color / 2 << 24` with Java's int shift: the high bits of 599 / 2 are lost).
pub fn fill_alpha(state: f32) -> u8 {
    let f = state / 2.0 * 0.9 + 0.1;
    let color = (255.0 * f) as i32;
    ((color / 2) & 0xFF) as u8
}
/// `TransparentButton.renderWidget`: state 2 normal, 4 hovered, 5 inactive.
pub fn button_alpha(active: bool, hovered: bool) -> u8 {
    fill_alpha(if !active {
        5.0
    } else if hovered {
        4.0
    } else {
        2.0
    })
}
/// `RenderUtils.getBackgroundColor`: 2 normal, 3 selected, 5 disabled.
pub fn row_alpha(enabled: bool, selected: bool) -> u8 {
    fill_alpha(if !enabled {
        5.0
    } else if selected {
        3.0
    } else {
        2.0
    })
}


/// `ExplorersCompassScreen.setupWidgets` / `tick`: where everything is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layout {
    pub width: i32,
    pub height: i32,
    pub search: Rect,
    pub group: Rect,
    pub next: Option<Rect>,
    pub sort: Rect,
    pub teleport: Option<Rect>,
    pub cancel: Rect,
    pub field: Rect,
    pub list: Rect,
}
pub const ROW_HEIGHT: i32 = 50;
pub const SCROLLBAR_WIDTH: i32 = 6;

pub fn layout(width: i32, height: i32, show_next: bool, show_teleport: bool) -> Layout {
    Layout {
        width,
        height,
        search: Rect::new(10, 40, 110, 20),
        group: Rect::new(10, 65, 110, 20),
        next: show_next.then(|| Rect::new(10, 90, 110, 20)),
        sort: Rect::new(10, if show_next { 125 } else { 100 }, 110, 20),
        teleport: show_teleport.then(|| Rect::new(width - 120, 10, 110, 20)),
        cancel: Rect::new(10, height - 30, 110, 20),
        field: Rect::new(130, 10, 140, 20),
        list: Rect::new(130, 40, width - 140, height - 50),
    }
}

/// What a click on the screen asks the game to do.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Action {
    None,
    /// `searchForStructure(key)`: `CompassSearchPacket(key, false)`, then the screen closes.
    Search(String),
    /// `searchForGroup(groupKey)`: `CompassSearchPacket(groupKey, true)`.
    SearchGroup(String),
    /// `searchForNext()`: `CompassSearchForNextPacket`.
    SearchNext,
    Teleport,
    Close,
    FocusSearch,
}

/// The state of `ExplorersCompassScreen`.
#[derive(Clone, Debug)]
pub struct Model {
    pub entries: Vec<Entry>,
    /// The search term in lower case.
    pub term: String,
    pub sorting: Sorting,
    pub rows: Vec<usize>,
    pub selected: Option<String>,
    pub scroll: f32,
    /// `foundStructureKey`: the structure of a compass that is FOUND.
    pub found_key: Option<String>,
    pub can_teleport: bool,
    pub max_next: i64,
    pub infinite_xp: bool,
    pub player_levels: i64,
    pub last_click: Option<(u64, String)>,
    pub scroll_drag: bool,
}

impl Model {
    pub fn new(entries: Vec<Entry>, found_key: Option<String>, can_teleport: bool, max_next: i64, infinite_xp: bool, player_levels: i64) -> Model {
        let mut m = Model {
            entries,
            term: String::new(),
            sorting: Sorting::Name,
            rows: Vec::new(),
            selected: None,
            scroll: 0.0,
            found_key: found_key.clone(),
            can_teleport,
            max_next,
            infinite_xp,
            player_levels,
            last_click: None,
            scroll_drag: false,
        };
        m.refresh(found_key.as_deref());
        m
    }
    pub fn enabled(&self, e: &Entry) -> bool {
        self.infinite_xp || self.player_levels >= e.xp.min(3)
    }
    /// `processSearchTerm`: `@` searches the source, otherwise the pretty name.
    pub fn matches(&self, e: &Entry) -> bool {
        match self.term.strip_prefix('@') {
            Some(rest) => e.source.to_lowercase().contains(rest),
            None => e.name.to_lowercase().contains(self.term.as_str()),
        }
    }
    fn sorted_rows(&self) -> Vec<usize> {
        let mut rows: Vec<usize> = (0..self.entries.len()).filter(|&i| self.matches(&self.entries[i])).collect();
        rows.sort_by(|&a, &b| Sorting::Name.compare(&self.entries[a], &self.entries[b]));
        rows.sort_by(|&a, &b| self.sorting.compare(&self.entries[a], &self.entries[b]));
        rows
    }
    pub fn refresh(&mut self, select: Option<&str>) {
        self.rows = self.sorted_rows();
        self.scroll = 0.0;
        self.selected = None;
        if let Some(key) = select
            && let Some(&i) = self.rows.iter().find(|&&i| self.entries[i].key == key)
            && self.enabled(&self.entries[i])
        {
            self.selected = Some(self.entries[i].key.clone());
        }
    }
    pub fn refresh_keep(&mut self) {
        let keep = self.selected.clone();
        self.refresh(keep.as_deref());
    }
    pub fn set_term(&mut self, text: &str) {
        self.term = text.to_lowercase();
        self.refresh_keep();
    }
    pub fn cycle_sorting(&mut self) {
        self.sorting = self.sorting.next();
        self.refresh_keep();
    }
    pub fn selected_entry(&self) -> Option<&Entry> {
        let key = self.selected.as_ref()?;
        self.entries.iter().find(|e| &e.key == key)
    }
    /// `tick`: the search buttons need a selection.
    pub fn search_active(&self) -> bool {
        self.selected.is_some()
    }
    /// `tick`: teleport and search for next: the selected structure is the one the compass found.
    pub fn found_selected(&self) -> bool {
        self.found_key.is_some() && self.selected.is_some() && self.selected == self.found_key
    }
    pub fn layout(&self, width: i32, height: i32) -> Layout {
        layout(width, height, self.max_next > 0, self.can_teleport)
    }
    pub fn max_position(&self) -> i32 {
        self.rows.len() as i32 * ROW_HEIGHT
    }
    pub fn max_scroll(&self, list: Rect) -> f32 {
        (self.max_position() - (list.h - 4)).max(0) as f32
    }
    pub fn set_scroll(&mut self, v: f32, list: Rect) {
        self.scroll = v.clamp(0.0, self.max_scroll(list));
    }
    pub fn wheel(&mut self, delta: f32, list: Rect) {
        let s = self.scroll - delta * ROW_HEIGHT as f32 / 2.0;
        self.set_scroll(s, list);
    }
    pub fn row_top(&self, index: usize, list: Rect) -> i32 {
        list.y + 4 - self.scroll as i32 + index as i32 * ROW_HEIGHT
    }
    pub fn row_at(&self, px: f32, py: f32, list: Rect) -> Option<usize> {
        let rel = (py - list.y as f32).floor() as i32 + self.scroll as i32 - 4;
        let row = rel / ROW_HEIGHT;
        let inside = px < (list.x + list.w) as f32 && px >= list.x as f32 && px <= (list.x + list.w) as f32;
        (inside && rel >= 0 && row >= 0 && (row as usize) < self.rows.len()).then_some(row as usize)
    }
    pub fn thumb(&self, list: Rect) -> Option<(i32, i32)> {
        let max = self.max_scroll(list) as i32;
        if max <= 0 {
            return None;
        }
        let span = list.h;
        let h = ((span * span) as f32 / self.max_position() as f32) as i32;
        let h = h.clamp(32, span - 8);
        let top = (self.scroll as i32 * (span - h) / max + list.y).max(list.y);
        Some((top, h))
    }
    pub fn drag_scroll(&mut self, dy: f32, list: Rect) {
        let max = self.max_scroll(list).max(1.0) as f64;
        let span = list.h;
        let k = (((span * span) as f32 / self.max_position().max(1) as f32) as i32).clamp(32, span - 8);
        let d1 = (max / f64::from(span - k)).max(1.0);
        self.set_scroll(self.scroll + (f64::from(dy) * d1) as f32, list);
    }

    /// A left click at (px, py) on a screen `width` x `height`; `now` in milliseconds.
    pub fn click(&mut self, px: f32, py: f32, width: i32, height: i32, now: u64) -> Action {
        let l = self.layout(width, height);
        if l.field.contains(px, py) {
            return Action::FocusSearch;
        }
        if l.search.contains(px, py) {
            return match self.selected.clone() {
                Some(key) if self.search_active() => Action::Search(key),
                _ => Action::None,
            };
        }
        if l.group.contains(px, py) {
            return match self.selected_entry() {
                Some(e) if self.search_active() => Action::SearchGroup(e.group_key.clone()),
                _ => Action::None,
            };
        }
        if let Some(n) = l.next
            && n.contains(px, py)
        {
            return if self.found_selected() { Action::SearchNext } else { Action::None };
        }
        if l.sort.contains(px, py) {
            self.cycle_sorting();
            return Action::None;
        }
        if let Some(t) = l.teleport
            && t.contains(px, py)
        {
            return if self.found_selected() { Action::Teleport } else { Action::None };
        }
        if l.cancel.contains(px, py) {
            return Action::Close;
        }
        let bar = Rect::new(l.list.x + l.list.w, l.list.y, SCROLLBAR_WIDTH, l.list.h);
        if bar.contains(px, py) {
            self.scroll_drag = self.max_scroll(l.list) > 0.0;
            return Action::None;
        }
        if let Some(row) = self.row_at(px, py, l.list) {
            let e = self.entries[self.rows[row]].clone();
            if self.enabled(&e) {
                self.selected = Some(e.key.clone());
                let double = self.last_click.as_ref().is_some_and(|(t, k)| *k == e.key && now.saturating_sub(*t) < 250);
                if double {
                    return Action::Search(e.key);
                }
                self.last_click = Some((now, e.key));
            }
        }
        Action::None
    }
}
