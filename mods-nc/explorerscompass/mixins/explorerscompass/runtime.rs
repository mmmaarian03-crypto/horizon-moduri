/// One line of the overlay: text, `0xRRGGBB` and the relative line (before the configured offset).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Line {
    pub text: String,
    pub color: u32,
    pub rel: i32,
}

pub const WHITE: u32 = 0xFFFFFF;
pub const GREY: u32 = 0xAAAAAA;

/// `RenderUtils.drawConfiguredStringOnHUD`: where a line is drawn, (x, y, right_aligned, shadow).
/// Right aligned lines are drawn without shadow (`drawStringRight`), left ones with it.
pub fn hud_position(rel: i32, gui_width: f32, text_width: f32) -> (f32, f32, bool) {
    let y = 5 + (rel + config::CLIENT_OVERLAY_LINE_OFFSET as i32) * 9;
    if config::CLIENT_OVERLAY_SIDE_LEFT {
        (7.0, (y + 2) as f32, true)
    } else {
        (gui_width - 5.0 - 2.0 - text_width, (y + 2) as f32, false)
    }
}


/// `ExplorersCompassOverlay.render`: the lines for a compass. `tr` gives `string.explorerscompass.<key>`;
/// `name` is `StructureUtils.getPrettyStructureName(structureKey)`; `player` is `player.blockPosition()`.
pub fn overlay_lines(data: &Data, player: Pos, name: &str, tr: &dyn Fn(&str) -> String) -> Vec<Line> {
    let line = |text: String, color: u32, rel: i32| Line { text, color, rel };
    let mut out = Vec::new();
    match data.state() {
        Some(State::Searching) => {
            out.push(line(tr("status"), WHITE, 0));
            out.push(line(tr("searching"), GREY, 1));
            out.push(line(tr("structure"), WHITE, 3));
            out.push(line(name.to_owned(), GREY, 4));
            out.push(line(tr("radius"), WHITE, 6));
            out.push(line(data.search_radius.to_string(), GREY, 7));
        }
        Some(State::Found) => {
            out.push(line(tr("status"), WHITE, 0));
            out.push(line(tr("found"), GREY, 1));
            out.push(line(tr("structure"), WHITE, 3));
            out.push(line(name.to_owned(), GREY, 4));
            if data.should_display_coordinates() {
                out.push(line(tr("coordinates"), WHITE, 6));
                out.push(line(format!("{}, {}", data.found_x, data.found_z), GREY, 7));
                out.push(line(tr("distance"), WHITE, 9));
                out.push(line(distance(player, data.found_x, data.found_z).to_string(), GREY, 10));
            }
        }
        Some(State::NotFound) => {
            out.push(line(tr("status"), WHITE, 0));
            out.push(line(tr("notFound"), GREY, 1));
            out.push(line(tr("structure"), WHITE, 3));
            out.push(line(name.to_owned(), GREY, 4));
            out.push(line(tr("radius"), WHITE, 6));
            out.push(line(data.search_radius.to_string(), GREY, 7));
        }
        _ => {}
    }
    out
}

