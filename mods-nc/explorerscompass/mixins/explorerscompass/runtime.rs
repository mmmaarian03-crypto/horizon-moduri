/// `CompassState`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum State {
    Inactive,
    Searching,
    Found,
    NotFound,
}
impl State {
    pub fn id(self) -> i32 {
        match self {
            State::Inactive => 0,
            State::Searching => 1,
            State::Found => 2,
            State::NotFound => 3,
        }
    }
    pub fn from_id(id: i32) -> Option<State> {
        Some(match id {
            0 => State::Inactive,
            1 => State::Searching,
            2 => State::Found,
            3 => State::NotFound,
            _ => return None,
        })
    }
}


/// The tags of the compass stack (`State`, `StructureKey`, `IsGroup`, `FoundX`, `FoundZ`, `PrevPos`, `Samples`,
/// `SearchRadius`, `DisplayCoordinates`, `CompassDamage`). A missing tag reads as the NBT default (0 / false).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Data {
    pub state: i32,
    /// `StructureKey`; `None` while the tag is missing (`getStructureKey` answers null).
    pub structure_key: Option<String>,
    pub is_group: bool,
    pub found_x: i32,
    pub found_z: i32,
    /// `PrevPos`; `None` while the tag is missing.
    pub prev_pos: Option<Vec<Pos>>,
    pub samples: i32,
    pub search_radius: i32,
    /// `DisplayCoordinates`; `None` reads as true.
    pub display_coordinates: Option<bool>,
    pub compass_damage: i32,
}
impl Data {
    pub fn state(&self) -> Option<State> {
        State::from_id(self.state)
    }
    pub fn should_display_coordinates(&self) -> bool {
        self.display_coordinates.unwrap_or(true)
    }
    /// `setSearching`.
    pub fn set_searching(&mut self, key: &str) {
        self.structure_key = Some(key.to_owned());
        self.state = State::Searching.id();
    }
    /// `setNotFound`.
    pub fn set_not_found(&mut self, radius: i32, samples: i32) {
        self.state = State::NotFound.id();
        self.search_radius = radius;
        self.samples = samples;
    }
    /// `succeed`: `setFound`, `setDisplayCoordinates`, `setIsGroup`, `setPrevPos`, `damageCompass`.
    #[allow(clippy::too_many_arguments)]
    pub fn succeed(&mut self, key: &str, is_group: bool, x: i32, z: i32, prev: Vec<Pos>, samples: i32, display: bool, durability: i64) {
        self.state = State::Found.id();
        self.structure_key = Some(key.to_owned());
        self.found_x = x;
        self.found_z = z;
        self.samples = samples;
        self.display_coordinates = Some(display);
        self.is_group = is_group;
        self.prev_pos = Some(prev);
        if durability > 0 {
            self.compass_damage += 1;
        }
    }
    /// `fail` when no worker is left: `setNotFound` and the structure key.
    pub fn fail(&mut self, key: &str, radius: i32, samples: i32) {
        self.set_not_found(radius, samples);
        self.structure_key = Some(key.to_owned());
    }
    /// The crouching use: `setState(INACTIVE)` and `remove("PrevPos")`.
    pub fn deactivate(&mut self) {
        self.state = State::Inactive.id();
        self.prev_pos = None;
    }
    pub fn is_broken(&self, durability: i64) -> bool {
        durability > 0 && i64::from(self.compass_damage) >= durability
    }
    pub fn bar_visible(&self, durability: i64) -> bool {
        durability > 0 && self.compass_damage > 0
    }
    /// `getBarWidth`: 13 * (1 - damage / max), 0 ~ 13; 13 without durability.
    pub fn bar_width(&self, durability: i64) -> i32 {
        if durability > 0 {
            ((13.0 * (1.0 - self.compass_damage as f32 / durability as f32)).round() as i32).clamp(0, 13)
        } else {
            13
        }
    }
    /// The angle target (`ExplorersCompassClient.getAngle`): the found place only while FOUND.
    pub fn target(&self) -> Option<(i32, i32)> {
        (self.state() == Some(State::Found)).then_some((self.found_x, self.found_z))
    }
}

