/// `java.util.Random` / `LegacyRandomSource` (what `WorldgenRandom` wraps for structure placement).
#[derive(Clone, Debug)]
pub struct JavaRandom {
    seed: u64,
}
const MASK48: u64 = (1u64 << 48) - 1;
impl JavaRandom {
    pub fn new(seed: i64) -> JavaRandom {
        JavaRandom { seed: (seed as u64 ^ 0x5DEE_CE66D) & MASK48 }
    }
    pub fn set_seed(&mut self, seed: i64) {
        self.seed = (seed as u64 ^ 0x5DEE_CE66D) & MASK48;
    }
    fn next(&mut self, bits: u32) -> i32 {
        self.seed = self.seed.wrapping_mul(0x5DEE_CE66D).wrapping_add(0xB) & MASK48;
        (self.seed >> (48 - bits)) as i32
    }
    pub fn next_int(&mut self) -> i32 {
        self.next(32)
    }
    /// `nextInt(bound)` for `bound > 0`.
    pub fn next_int_bound(&mut self, bound: i32) -> i32 {
        let mut r = self.next(31);
        let m = bound - 1;
        if bound & m == 0 {
            ((i64::from(bound) * i64::from(r)) >> 31) as i32
        } else {
            let mut u = r;
            loop {
                r = u % bound;
                if u.wrapping_sub(r).wrapping_add(m) >= 0 {
                    break;
                }
                u = self.next(31);
            }
            r
        }
    }
}

/// `StructurePlacement` of a structure set (`worldgen/structure_set/*.json`).
#[derive(Clone, Debug, PartialEq)]
pub enum Placement {
    /// `RandomSpreadStructurePlacement`: spacing, separation, salt, `spread_type` triangular.
    RandomSpread { spacing: i32, separation: i32, salt: i32, triangular: bool },
    /// `ConcentricRingsStructurePlacement` (strongholds): the chunks come from the world.
    Rings,
    /// Any other placement: searched chunk by chunk.
    Generic,
}

/// A structure set: its id, its placement and the structures a request has in it.
#[derive(Clone, Debug, PartialEq)]
pub struct SetDef {
    pub id: String,
    pub placement: Placement,
    pub structures: Vec<String>,
}

/// `RandomSpreadStructurePlacement.getPotentialStructureChunk(seed, chunkX, chunkZ)`.
pub fn potential_chunk(spacing: i32, separation: i32, salt: i32, triangular: bool, seed: i64, chunk_x: i32, chunk_z: i32) -> [i32; 2] {
    let (i, j) = (chunk_x.div_euclid(spacing), chunk_z.div_euclid(spacing));
    let mut r = JavaRandom::new(0);
    // WorldgenRandom.setLargeFeatureWithSalt
    let l = i64::from(i)
        .wrapping_mul(341_873_128_712)
        .wrapping_add(i64::from(j).wrapping_mul(132_897_987_541))
        .wrapping_add(seed)
        .wrapping_add(i64::from(salt));
    r.set_seed(l);
    let k = spacing - separation;
    let spread = |r: &mut JavaRandom| {
        if triangular {
            (r.next_int_bound(k) + r.next_int_bound(k)) / 2
        } else {
            r.next_int_bound(k)
        }
    };
    let a = spread(&mut r);
    let b = spread(&mut r);
    [i * spacing + a, j * spacing + b]
}

