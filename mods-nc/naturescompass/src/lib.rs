/// `BiomeSource.getNoiseBiome` over quart positions (`QuartPos.fromBlock` = `>> 2`): the biome id of each, `None` when unknown.
pub trait BiomeSource {
    fn noise_biomes(&mut self, quarts: &[[i32; 3]]) -> Vec<Option<String>>;
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Dir {
    Up,
    North,
    East,
    South,
    West,
}
impl Dir {
    /// `Direction.getClockWise` (around Y).
    fn clockwise(self) -> Dir {
        match self {
            Dir::North => Dir::East,
            Dir::East => Dir::South,
            Dir::South => Dir::West,
            Dir::West => Dir::North,
            Dir::Up => Dir::Up,
        }
    }
}

/// How a worker ended.
#[derive(Clone, Debug, PartialEq)]
pub enum Finish {
    /// `NaturesCompassItem.succeed(stack, player, biomeKey, x, z, prevPos, samples, displayCoordinates)`.
    Found { x: i32, z: i32, prev_pos: Vec<Pos>, samples: i32 },
    /// `NaturesCompassItem.fail(stack, player, biomeKey, radius, samples)` (radius rounded to 500).
    Failed { radius: i32, samples: i32 },
}

/// `BiomeSearchWorker`.
#[derive(Clone, Debug)]
pub struct Worker {
    pub biome: String,
    sample_space: i32,
    max_samples: i64,
    max_radius: i64,
    start: Pos,
    pub samples: i32,
    next_length: i32,
    direction: Dir,
    x: i32,
    z: i32,
    y_values: Vec<i32>,
    length: i32,
    pub finished: bool,
    last_radius_threshold: i32,
    prev_pos: Vec<Pos>,
    checking: bool,
    candidate: Pos,
    prev_index: usize,
    check_index: i32,
    check_samples: i32,
    non_matching: i32,
    /// `setSearchRadius` calls made while working, taken by the adapter.
    pub radius_updates: Vec<i32>,
}

impl Worker {
    /// `new BiomeSearchWorker(level, player, stack, biomeKey, startPos, prevPos)`; `min_y` is
    /// `level.getMinBuildHeight()`, `max_y` `level.getMaxBuildHeight()`.
    pub fn new(biome: &str, start: Pos, prev_pos: Vec<Pos>, min_y: i32, max_y: i32) -> Worker {
        Self::with(biome, start, prev_pos, min_y, max_y, config::GENERAL_SAMPLE_SPACE_MODIFIER, config::GENERAL_RADIUS_MODIFIER, config::GENERAL_MAX_SAMPLES)
    }
    /// The same with explicit modifiers (tests).
    #[allow(clippy::too_many_arguments)]
    pub fn with(biome: &str, start: Pos, prev_pos: Vec<Pos>, min_y: i32, max_y: i32, sample_mod: i64, radius_mod: i64, max_samples: i64) -> Worker {
        let sample_space = (sample_mod * BIOME_SIZE) as i32;
        Worker {
            biome: biome.to_owned(),
            sample_space,
            max_samples,
            max_radius: radius_mod * BIOME_SIZE,
            start,
            samples: 0,
            next_length: sample_space,
            direction: Dir::Up,
            x: start[0],
            z: start[2],
            y_values: out_from_origin(start[1], min_y + 1, max_y, 64),
            length: 0,
            finished: false,
            last_radius_threshold: 0,
            prev_pos,
            checking: false,
            candidate: [0; 3],
            prev_index: 0,
            check_index: 0,
            check_samples: 0,
            non_matching: 0,
            radius_updates: Vec::new(),
        }
    }

    pub fn radius(&self) -> i32 {
        distance(self.start, self.x, self.z)
    }
    pub fn round_radius(radius: i32, round_to: i32) -> i32 {
        (radius / round_to) * round_to
    }
    /// `start()`: with no radius or no sample space the search fails at once.
    pub fn start(&mut self) -> Option<Finish> {
        if self.max_radius > 0 && self.sample_space > 0 {
            None
        } else {
            Some(self.fail())
        }
    }
    /// `hasWork()`.
    pub fn has_work(&self) -> bool {
        !self.biome.is_empty() && !self.finished && i64::from(self.radius()) <= self.max_radius && i64::from(self.samples) <= self.max_samples
    }

    fn matches(&self, name: &Option<String>) -> bool {
        name.as_deref() == Some(self.biome.as_str())
    }
    fn biome_at(&self, src: &mut impl BiomeSource, x: i32, y: i32, z: i32) -> bool {
        let found = src.noise_biomes(&[[x >> 2, y >> 2, z >> 2]]);
        found.first().is_some_and(|n| self.matches(n))
    }

    /// One call of `doWork()`. `Some` when the worker finished during it.
    pub fn do_work(&mut self, src: &mut impl BiomeSource) -> Option<Finish> {
        if self.checking {
            return self.check_connections(src);
        }
        if self.has_work() {
            match self.direction {
                Dir::North => self.z -= self.sample_space,
                Dir::East => self.x += self.sample_space,
                Dir::South => self.z += self.sample_space,
                Dir::West => self.x -= self.sample_space,
                Dir::Up => {}
            }
            let ys = self.y_values.clone();
            for y in ys {
                if self.biome_at(src, self.x, y, self.z) {
                    if self.prev_pos.is_empty() {
                        self.prev_pos.push([self.x, y, self.z]);
                        return Some(self.succeed());
                    }
                    self.checking = true;
                    self.candidate = [self.x, y, self.z];
                    self.prev_index = 0;
                    self.check_index = 0;
                    return None;
                }
            }
            self.finish_sample();
        }
        if self.has_work() {
            return None;
        }
        if !self.finished {
            return Some(self.fail());
        }
        None
    }


    /// `checkConnections()`: one operation toward deciding whether the candidate belongs to a place found before.
    fn check_connections(&mut self, src: &mut impl BiomeSource) -> Option<Finish> {
        if self.prev_index >= self.prev_pos.len() {
            // Through all the earlier places without one that is connected: the candidate is accepted.
            self.prev_pos.push(self.candidate);
            self.checking = false;
            return Some(self.succeed());
        }
        let prev = self.prev_pos[self.prev_index];
        let dx = self.candidate[0] - prev[0];
        let dz = self.candidate[2] - prev[2];
        if self.check_index == 0 {
            // Within two sample spaces of an earlier place: connected, the candidate is skipped.
            let dist = (f64::from(dx) * f64::from(dx) + f64::from(dz) * f64::from(dz)).sqrt();
            if dist <= f64::from(self.sample_space) * 2.0 {
                self.checking = false;
                self.finish_sample();
                return None;
            }
            self.check_samples = (dist / f64::from(self.sample_space)) as i32;
            self.non_matching = 0;
            self.check_index = 1;
            return None;
        }
        if self.check_index >= self.check_samples {
            // All the line samples without a large enough gap: connected, the candidate is skipped.
            self.checking = false;
            self.finish_sample();
            return None;
        }
        // One point on the straight line from the earlier place to the candidate.
        let t = f64::from(self.check_index) / f64::from(self.check_samples);
        let sx = (f64::from(prev[0]) + f64::from(dx) * t) as i32;
        let sz = (f64::from(prev[2]) + f64::from(dz) * t) as i32;
        let mut found = false;
        for y in self.y_values.clone() {
            if self.biome_at(src, sx, y, sz) {
                found = true;
                break;
            }
        }
        if found {
            self.non_matching = 0;
        } else {
            self.non_matching += 1;
            // A stretch of non-matching samples of 25% of all (at most 10): not connected to that place.
            let threshold = (self.check_samples / 4).clamp(1, 10);
            if self.non_matching >= threshold {
                self.prev_index += 1;
                self.check_index = 0;
                self.non_matching = 0;
                return None;
            }
        }
        self.check_index += 1;
        None
    }

    /// `finishSample()`: counts the sample, turns the spiral, tells the compass the radius.
    fn finish_sample(&mut self) {
        self.samples += 1;
        self.length += self.sample_space;
        if self.length >= self.next_length {
            if self.direction == Dir::Up {
                self.direction = Dir::North;
            } else {
                self.next_length += self.sample_space;
                self.direction = self.direction.clockwise();
            }
            self.length = 0;
        }
        let radius = self.radius();
        if radius > 500 && radius / 500 > self.last_radius_threshold {
            self.radius_updates.push(Self::round_radius(radius, 500));
            self.last_radius_threshold = radius / 500;
        }
    }

    fn succeed(&mut self) -> Finish {
        self.finished = true;
        Finish::Found { x: self.x, z: self.z, prev_pos: self.prev_pos.clone(), samples: self.samples }
    }
    fn fail(&mut self) -> Finish {
        self.finished = true;
        Finish::Failed { radius: Self::round_radius(self.radius(), 500), samples: self.samples }
    }
    /// `stop()`.
    pub fn stop(&mut self) {
        self.finished = true;
    }
}

