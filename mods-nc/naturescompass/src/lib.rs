/// `convertToRegex(glob)` + `String.matches`: `*` any run, `?` one character, everything else literal.
/// (The original pastes other characters into a regular expression; the only one it escapes is `.`.)
pub fn glob_matches(glob: &str, text: &str) -> bool {
    fn go(g: &[char], t: &[char]) -> bool {
        match g.first() {
            None => t.is_empty(),
            Some('*') => (0..=t.len()).any(|i| go(&g[1..], &t[i..])),
            Some('?') => !t.is_empty() && go(&g[1..], &t[1..]),
            Some(c) => t.first() == Some(c) && go(&g[1..], &t[1..]),
        }
    }
    let g: Vec<char> = glob.chars().collect();
    let t: Vec<char> = text.chars().collect();
    go(&g, &t)
}

/// `BiomeUtils.biomeKeyIsBlacklisted`.
pub fn blacklisted(blacklist: &[&str], key: &str) -> bool {
    blacklist.iter().any(|g| glob_matches(g, key))
}

/// `BiomeUtils.parseXpLevelOverridesConfig`: "regex,levels" pairs in order (a `HashMap` in the original,
/// iterated in hash order; the entries are tried in the order given here, first match wins, like a
/// config with one matching entry).
pub fn parse_xp_overrides(list: &[&str]) -> Vec<(String, i64)> {
    list.iter()
        .filter_map(|s| {
            let mut parts = s.split(',');
            let (key, levels) = (parts.next()?, parts.next()?);
            if parts.next().is_some() {
                return None;
            }
            Some((key.to_owned(), levels.parse::<i64>().ok()?))
        })
        .collect()
}

/// `BiomeUtils.getXpLevelsForBiome`.
pub fn xp_levels_for(key: &str, default: i64, overrides: &[(String, i64)]) -> i64 {
    let mut levels = default;
    for (glob, n) in overrides {
        if glob_matches(glob, key) {
            levels = *n;
            if levels > 3 {
                levels = 3;
            }
            break;
        }
    }
    levels
}

/// `XP levels` for the pack's config.
pub fn xp_levels(key: &str) -> i64 {
    xp_levels_for(key, config::GENERAL_DEFAULT_XP_LEVELS, &parse_xp_overrides(config::GENERAL_PER_BIOME_XP_LEVELS))
}

/// `BiomeUtils.getNoiseBiome` radius: `(int) Mth.sqrt((float) startPos.distSqr(new BlockPos(x, startPos.getY(), z)))`.
pub fn distance(start: Pos, x: i32, z: i32) -> i32 {
    let dx = f64::from(x) - f64::from(start[0]);
    let dz = f64::from(z) - f64::from(start[2]);
    let d2 = (dx * dx + dz * dz) as f32;
    (f64::from(d2).sqrt() as f32) as i32
}

/// `Mth.outFromOrigin(origin, lower, upper, step)`.
pub fn out_from_origin(origin: i32, lower: i32, upper: i32, step: i32) -> Vec<i32> {
    let center = origin.clamp(lower, upper);
    let mut out = Vec::new();
    let mut cursor = center;
    loop {
        let distance = (center - cursor).abs();
        if !(center - distance >= lower || center + distance <= upper) {
            return out;
        }
        out.push(cursor);
        let negative = cursor <= center;
        let can_move_positive = center + distance + step <= upper;
        let mut next = center + distance + step;
        if !negative || !can_move_positive {
            let attempt = center - distance - if negative { step } else { 0 };
            if attempt >= lower {
                next = attempt;
            }
        }
        cursor = next;
    }
}

