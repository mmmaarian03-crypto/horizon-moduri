/// `CompassState`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum State {
    Inactive,
    Searching,
    Found,
    NotFound,
}
impl State {
    pub fn id(self) -> i32 {
        match self {
            State::Inactive => 0,
            State::Searching => 1,
            State::Found => 2,
            State::NotFound => 3,
        }
    }
    pub fn from_id(id: i32) -> Option<State> {
        Some(match id {
            0 => State::Inactive,
            1 => State::Searching,
            2 => State::Found,
            3 => State::NotFound,
            _ => return None,
        })
    }
}

/// The tags of the compass stack (`State`, `BiomeKey`, `FoundX`, `FoundZ`, `PrevPos`, `Samples`, `SearchRadius`,
/// `DisplayCoordinates`, `CompassDamage`). A missing tag reads as the NBT default (0 / ""), as in the original.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Data {
    pub state: i32,
    pub biome_key: String,
    pub found_x: i32,
    pub found_z: i32,
    /// `PrevPos`; `None` while the tag is missing (`searchForNextBiome` needs it).
    pub prev_pos: Option<Vec<Pos>>,
    pub samples: i32,
    pub search_radius: i32,
    /// `DisplayCoordinates`; `None` reads as true (`shouldDisplayCoordinates`).
    pub display_coordinates: Option<bool>,
    pub compass_damage: i32,
}
impl Data {
    /// `getState`: `CompassState.fromID`, null for an unknown id.
    pub fn state(&self) -> Option<State> {
        State::from_id(self.state)
    }
    pub fn should_display_coordinates(&self) -> bool {
        self.display_coordinates.unwrap_or(true)
    }
    /// `setSearching`.
    pub fn set_searching(&mut self, biome: &str) {
        self.biome_key = biome.to_owned();
        self.state = State::Searching.id();
    }
    /// `succeed`: found; the damage of the compass counts.
    pub fn succeed(&mut self, biome: &str, x: i32, z: i32, prev: Vec<Pos>, samples: i32, display: bool, durability: i64) {
        self.state = State::Found.id();
        self.biome_key = biome.to_owned();
        self.found_x = x;
        self.found_z = z;
        self.prev_pos = Some(prev);
        self.samples = samples;
        self.display_coordinates = Some(display);
        if durability > 0 {
            self.compass_damage += 1;
        }
    }
    /// `fail`.
    pub fn fail(&mut self, biome: &str, radius: i32, samples: i32) {
        self.state = State::NotFound.id();
        self.biome_key = biome.to_owned();
        self.search_radius = radius;
        self.samples = samples;
    }
    /// `isBroken`.
    pub fn is_broken(&self, durability: i64) -> bool {
        durability > 0 && i64::from(self.compass_damage) >= durability
    }
    /// `isBarVisible` / `getBarWidth` / `getBarColor`'s inputs: the damage fraction.
    pub fn bar_visible(&self, durability: i64) -> bool {
        durability > 0 && self.compass_damage > 0
    }
    /// `getBarWidth`: 13 * (1 - damage / max), 0 ~ 13; 13 without durability.
    pub fn bar_width(&self, durability: i64) -> i32 {
        if durability > 0 {
            ((13.0 * (1.0 - self.compass_damage as f32 / durability as f32)).round() as i32).clamp(0, 13)
        } else {
            13
        }
    }
    /// The angle target (`NaturesCompassClient.getAngle`): the found place only while FOUND.
    pub fn target(&self) -> Option<(i32, i32)> {
        (self.state() == Some(State::Found)).then_some((self.found_x, self.found_z))
    }
}

