/// One row of the list: what `BiomeSearchEntry` shows.
#[derive(Clone, Debug, PartialEq)]
pub struct Entry {
    pub key: String,
    /// `BiomeUtils.getBiomeName` (the sort value of "Name").
    pub name: String,
    /// `BiomeUtils.getBiomeNameForDisplay`.
    pub display: String,
    /// `BiomeUtils.getBiomeSource`.
    pub source: String,
    /// `BiomeUtils.getBiomeTags`.
    pub tags: String,
    /// `BiomeUtils.dimensionKeysToString`.
    pub dimensions: String,
    pub xp: i64,
    pub rainfall: f32,
    pub temperature: f32,
}

/// `BiomeUtils.getBiomeNameForDisplay` with `fixBiomeNames`: a space between a lowercase letter and an uppercase one.
pub fn fix_biome_name(original: &str) -> String {
    if !config::CLIENT_FIX_BIOME_NAMES {
        return original.to_owned();
    }
    let mut fixed = String::new();
    let mut pre = ' ';
    for c in original.chars() {
        if c.is_uppercase() && pre.is_lowercase() && pre.is_alphabetic() {
            fixed.push(' ');
        }
        fixed.push(c);
        pre = c;
    }
    fixed
}

/// `WordUtils.capitalize`: the first letter of each word (spaces separate words).
pub fn capitalize(text: &str) -> String {
    let mut out = String::new();
    let mut start = true;
    for c in text.chars() {
        if c.is_whitespace() {
            start = true;
            out.push(c);
        } else if start {
            out.extend(c.to_uppercase());
            start = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// The sortings, in the order of `ISorting.next()`: Name, Source, Tags, Dimension, XP levels, Rainfall, Temperature.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Sorting {
    Name,
    Source,
    Tags,
    Dimension,
    Xp,
    Rainfall,
    Temperature,
}
impl Sorting {
    pub fn next(self) -> Sorting {
        match self {
            Sorting::Name => Sorting::Source,
            Sorting::Source => Sorting::Tags,
            Sorting::Tags => Sorting::Dimension,
            Sorting::Dimension => Sorting::Xp,
            Sorting::Xp => Sorting::Rainfall,
            Sorting::Rainfall => Sorting::Temperature,
            Sorting::Temperature => Sorting::Name,
        }
    }
    /// The language key (`string.naturescompass.<key>`) and the English text of `getLocalizedName`.
    pub fn label(self) -> (&'static str, &'static str) {
        match self {
            Sorting::Name => ("name", "Name"),
            Sorting::Source => ("source", "Source"),
            Sorting::Tags => ("tags", "Tags"),
            Sorting::Dimension => ("dimension", "Dimension"),
            Sorting::Xp => ("levels", "Levels"),
            Sorting::Rainfall => ("rainfall", "Rainfall"),
            Sorting::Temperature => ("temperature", "Temperature"),
        }
    }
    /// `getValue` as shown in the list.
    pub fn value(self, e: &Entry) -> String {
        match self {
            Sorting::Name => e.name.clone(),
            Sorting::Source => e.source.clone(),
            Sorting::Tags => e.tags.clone(),
            Sorting::Dimension => e.dimensions.clone(),
            Sorting::Xp => e.xp.to_string(),
            Sorting::Rainfall => java_float(e.rainfall),
            Sorting::Temperature => java_float(e.temperature),
        }
    }
    pub fn compare(self, a: &Entry, b: &Entry) -> std::cmp::Ordering {
        match self {
            Sorting::Name => a.name.cmp(&b.name),
            Sorting::Source => a.source.cmp(&b.source),
            Sorting::Tags => a.tags.cmp(&b.tags),
            Sorting::Dimension => a.dimensions.cmp(&b.dimensions),
            // `String.valueOf(level)` compared as text.
            Sorting::Xp => a.xp.to_string().cmp(&b.xp.to_string()),
            Sorting::Rainfall => a.rainfall.total_cmp(&b.rainfall),
            Sorting::Temperature => a.temperature.total_cmp(&b.temperature),
        }
    }
    /// The list shows the dimension under these sortings instead of the sort value.
    pub fn shows_dimension(self) -> bool {
        matches!(self, Sorting::Name | Sorting::Source | Sorting::Tags | Sorting::Dimension)
    }
}

/// `Float.toString` for the values biomes have (0.5, 0.8, -0.5, 2.0 ...).
pub fn java_float(v: f32) -> String {
    if v == v.trunc() && v.abs() < 1.0e7 {
        format!("{v:.1}")
    } else {
        format!("{v}")
    }
}

