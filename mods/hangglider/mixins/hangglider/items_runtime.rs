/// A stack as the rules read it.
#[derive(Clone, Debug, PartialEq)]
pub struct Stack {
    pub item: String,
    pub damage: u32,
}

/// `PlayerGlidingHelper.isValidGlider`: a `GliderItem` that `ElytraItem.isFlyEnabled`
/// (`damage < maxDamage - 1`).
pub fn valid(stack: Option<&Stack>) -> bool {
    stack.is_some_and(|s| glider(&s.item).is_some_and(|g| s.damage + 1 < g.durability))
}

/// A hand.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Hand {
    Main,
    Off,
}

/// `GlidingCapability` of a player.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct State {
    pub deployed: bool,
    pub gliding: bool,
}

/// What a use of an item does (`GliderItem.use`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Use {
    /// Not a glider: the game goes on.
    Pass,
    /// An elytra on the chest: `Proxy.addElytraWidget` (the client's elytra-and-cross icon), `FAIL`.
    Elytra,
    /// A broken glider: `FAIL`.
    Fail,
    /// The glider opens / closes (`sidedSuccess`: the hand swings).
    Toggled,
}

/// `GliderItem.use` with `stack` in the used hand.
pub fn on_use(state: &mut State, stack: Option<&Stack>, chest_elytra: bool) -> Use {
    if !stack.is_some_and(|s| glider(&s.item).is_some()) {
        return Use::Pass;
    }
    if chest_elytra {
        Use::Elytra
    } else if valid(stack) {
        state.deployed = !state.deployed;
        Use::Toggled
    } else {
        Use::Fail
    }
}

/// `PlayerGlidingHelper.getGliderHoldingHand`: the first hand (main, then off) holding a `GliderItem`.
pub fn glider_hand(main: Option<&Stack>, off: Option<&Stack>) -> Option<Hand> {
    let is = |s: Option<&Stack>| s.is_some_and(|s| glider(&s.item).is_some());
    if is(main) {
        Some(Hand::Main)
    } else if is(off) {
        Some(Hand::Off)
    } else {
        None
    }
}

/// The player at the end of his tick, as the rules read him.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Player {
    pub position: [f64; 3],
    pub velocity: [f64; 3],
    pub yaw: f32,
    pub on_ground: bool,
    pub passenger: bool,
    pub levitation: bool,
    /// `getAbilities().flying`
    pub flying: bool,
    pub in_water: bool,
    /// `isDescending()` = Shift held
    pub descending: bool,
    /// `level().isRaining()`
    pub raining: bool,
    /// The chest slot holds an `ElytraItem`.
    pub chest_elytra: bool,
}

/// `PlayerGlidingHelper.isAllowedToGlide`.
pub fn allowed_to_glide(p: &Player) -> bool {
    !p.on_ground && !p.passenger && !p.levitation && !p.flying && !p.in_water && p.velocity[1] < 0.0
}

/// What the end of a player's tick does (`PlayerGlidingHandler.onPlayerTick$End`).
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Outcome {
    /// The new delta movement (`handleGlidingMovement`).
    pub velocity: Option<[f64; 3]>,
    /// The new yaw (the wind).
    pub yaw: Option<f32>,
    /// `fallDistance = 1.0F`.
    pub fall_distance_one: bool,
    /// The glider in this hand wears one point (`handleGliderDurability`, the server's).
    pub wear: Option<Hand>,
}

/// `PlayerTickEvents.END`: `state` is the player's capability, `main`/`off` his hands; `server` is the
/// side that owns the items (`!level.isClientSide`); `roll(n)` = `player.getRandom().nextInt(n)`.
pub fn end_tick(
    state: &mut State,
    main: Option<&Stack>,
    off: Option<&Stack>,
    p: &Player,
    server: bool,
    roll: impl FnOnce(i32) -> i32,
) -> Outcome {
    let mut out = Outcome::default();
    if state.deployed {
        let hand = glider_hand(main, off);
        let stack = match hand {
            Some(Hand::Main) => main,
            Some(Hand::Off) => off,
            None => None,
        };
        if valid(stack) && !p.chest_elytra {
            if allowed_to_glide(p) {
                state.gliding = true;
                let stack = stack.expect("valid");
                let g = glider(&stack.item).expect("glider");
                let (velocity, yaw) = gliding_movement(p, stack, g);
                out.velocity = Some(velocity);
                out.yaw = Some(yaw);
                out.fall_distance_one = velocity[1] > -0.5;
                if server && g.config.consume_durability && roll(g.config.durability_use_interval) == 0 {
                    out.wear = hand;
                }
                return out;
            }
        } else {
            state.deployed = false;
        }
    }
    state.gliding = false;
    out
}

/// `PlayerGlidingHandler.handleGlidingMovement` (with `WindHelper.applyWind` first): the new delta
/// movement and yaw.
pub fn gliding_movement(p: &Player, stack: &Stack, g: &Glider) -> ([f64; 3], f32) {
    let c = &g.config;
    let (horizontal, vertical) = if p.descending {
        (c.fast_horizontal_speed, c.fast_vertical_speed)
    } else {
        (c.horizontal_speed, c.vertical_speed)
    };
    let yaw = (f64::from(p.yaw) + wind(p, stack, g)) as f32;
    let [mx, my, mz] = p.velocity;
    let angle = (f64::from(yaw + 90.0)).to_radians();
    let dx = angle.cos() * horizontal;
    let dz = angle.sin() * horizontal;
    let mut v = [mx + dx, my * vertical, mz + dz];
    if config::WIND_ALLOW_AIR_RESISTANCE {
        v = [v[0] * c.air_resistance, v[1], v[2] * c.air_resistance];
    }
    (v, yaw)
}

/// `WindHelper.applyWind`: the yaw change (degrees) the wind gives this tick.
pub fn wind(p: &Player, stack: &Stack, g: &Glider) -> f64 {
    if !config::WIND_ALLOW_WIND {
        return 0.0;
    }
    let [x, y, z] = p.position;
    let mut noise = noise().eval(x / config::WIND_GUST_SIZE, z / config::WIND_GUST_SIZE);
    noise *= if p.raining {
        config::WIND_RAINING_MULTIPLIER * config::WIND_FREQUENCY
    } else {
        config::WIND_FREQUENCY
    };
    let velocity = (p.velocity[0].powi(2) + p.velocity[2].powi(2)).sqrt();
    let speed_stabilized = noise * 1.0 / ((velocity * config::WIND_SPEED_MULTIPLIER) + 1.0);
    let height = if y < 256.0 {
        (y / 256.0) * config::WIND_HEIGHT_MULTIPLIER
    } else {
        config::WIND_HEIGHT_MULTIPLIER
    };
    let mut wind = speed_stabilized * height;
    let damaged = stack.damage > 0;
    let additional = if damaged {
        config::WIND_DURABILITY_MULTIPLIER * (f64::from(stack.damage) / f64::from(g.durability))
    } else {
        0.0
    };
    wind *= 1.0 + additional;
    wind *= config::WIND_OVERALL_POWER;
    wind *= g.config.wind_modifier;
    wind
}

/// `FovModifierHandler`: the field of view modifier while gliding.
pub fn fov(state: &State, descending: bool, modifier: f32) -> f32 {
    if state.gliding {
        modifier * if descending { 1.1 } else { 1.05 }
    } else {
        modifier
    }
}

